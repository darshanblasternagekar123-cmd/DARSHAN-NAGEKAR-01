# Read the radius of a circle and calculate the area and circumference of the circle.

# input section
r=float(input("Enter the radius of the circle:"))

# processing section
pi=3.14
area=pi*r*r
circumference=2*pi*r

# output section
print("Radius of the circle is:\t",r)
print("Area of the circle is:\t",area)
print("Circumference of the circle is:\t",circumference)    
